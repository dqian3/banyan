// MakeDefaultConfig returns Config object with few default values
// only used by init() and master
func MakeDefaultConfig() Config {
	return Config{
		Hasher:  "sha3_256",
		Signer:  "ECDSA_P256",
		MemSize: 100000,
	}
}

