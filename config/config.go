var configFile = flag.String("config", "config.json", "Configuration file for bamboo replica. Defaults to config.json.")

// Config contains every system configuration
type Config struct {
	Addrs     map[identity.NodeID]string `json:"address"`      // address for node communication
	HTTPAddrs map[identity.NodeID]string `json:"http_address"` // address for client server communication

	ExperimentDuration int    `json:"experiment_duration"`
	Timeout            int    `json:"timeout"`
	ByzNo              int    `json:"byzNo"`
	Strategy           string `json:"strategy"`
	PayloadSize        int    `json:"payload_size"`
	// Workload selects where block payload comes from: "generated" (the
	// fork's default — each leader fills a block with random bytes, so
	// offered load is set by payload_size alone) or "client", where blocks
	// carry real client requests drained from the mempool and payload_size
	// becomes a per-block byte budget. Empty means "generated".
	Workload string `json:"workload"`
	// ExitAfter, when > 0, is how many seconds past the end of the measurement
	// window a node stays alive before exiting on its own.
	//
	// A banyan node never stops: with no clients it still proposes a block per
	// consensus round, which on loopback is thousands a second, and its
	// blockchain state grows with them. A node orphaned by a crashed harness
	// therefore does not idle — it consumed 1.6 GB within four minutes during
	// development, and four of them took most of a laptop's memory. This bound
	// makes an orphan self-limiting; the harness still kills nodes normally,
	// and sets this well past its own report collection.
	ExitAfter int `json:"exit_after"`
	// MemSize bounds the per-node request queue. Beyond it a node sheds new
	// requests and tells the client, rather than absorbing unbounded backlog
	// and reporting it as latency.
	MemSize int `json:"mem_size"`
	// ClientReplyCount is how many nodes reply per committed request: the
	// block's proposer, which received it, and the nodes after it in node
	// order. 0 means f+1.
	ClientReplyCount int `json:"client_reply_count"`
	F                int `json:"f"`
	P       int `json:"p"`
	N       int // total number of nodes

	// Exported, and tagged, because encoding/json silently skips unexported
	// fields: while these were `hasher`/`signer` the decoder in Load() left
	// them at their MakeDefaultConfig values, so every run signed with
	// ECDSA_P256 no matter what config.json asked for -- including the runs
	// the harness launched with `signer: "NONE"` to measure the cost of
	// signing by its absence.
	Hasher string `json:"hasher"`
	Signer string `json:"signer"`
}

